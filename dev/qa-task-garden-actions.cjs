'use strict';
const fs = require('node:fs');
const path = require('node:path');
const assert = require('node:assert/strict');
const { chromium } = require(process.env.TRACER_QA_PLAYWRIGHT || 'playwright');
const root = path.resolve(__dirname, '..');
const temporary = fs.mkdtempSync(path.join(root, '.cache/task-garden-actions-'));
Object.assign(process.env, { DOCS_PORTAL_HOST: '127.0.0.1', DOCS_PORTAL_SKIN: 'tracer', DOCS_PORTAL_DATA_DIR: path.join(temporary, 'data'), DOCS_PORTAL_STATE_FILE: path.join(temporary, 'bookmarks.json') });
const { server } = require('../server');

(async () => {
  await new Promise(resolve => server.listen(0, '127.0.0.1', resolve));
  const browser = await chromium.launch({ channel: 'msedge', headless: true });
  try {
    const page = await browser.newPage({ viewport: { width: 1440, height: 1000 } });
    const errors = []; page.on('pageerror', error => errors.push(error.message));
    const saved = () => page.waitForFunction(() => !Tracer.store.dirty && !Tracer.store.inflight);
    const state = id => page.evaluate(id => ({ task: TracerModel.findTask(Tracer.store.data, id), seed: TaskGarden.read(Tracer.store.data).seeds.find(s => s.taskId === id) }), id);
    const choose = (id, status) => page.locator('.card[data-id="' + id + '"] .card-move').selectOption(status);
    const decision = answer => page.locator('[data-task-action="' + answer + '"]').click();
    await page.goto('http://127.0.0.1:' + server.address().port);
    await page.waitForFunction(() => window.Tracer?.store?.data);
    await page.selectOption('#language-select', 'zh');
    const ids = await page.evaluate(() => {
      const M = TracerModel, ws = Tracer.store.data;
      const p = M.addProject(ws, { name: '花朵收藏测试' });
      const q = M.addProject(ws, { name: 'Keep other project' });
      const a = M.addTask(ws, { title: 'First flower', projectId: p.id, status: 'doing' });
      const b = M.addTask(ws, { title: 'Second flower', projectId: p.id, status: 'doing' });
      const c = M.addTask(ws, { title: 'Kept flower', projectId: q.id, status: 'doing' });
      M.moveTask(ws, c.id, 'done');
      Tracer.touch(); Tracer.redraw(); Tracer.openProject(p.id);
      return { p: p.id, q: q.id, a: a.id, b: b.id, c: c.id };
    });
    await saved();
    const original = await state(ids.a);
    await choose(ids.a, 'todo');
    assert.equal((await state(ids.a)).task.status, 'doing', 'opening destructive confirmation is read-only');
    await decision('cancel');
    assert.deepEqual(await state(ids.a), original, 'cancel restores the select without touching seed or task');
    await choose(ids.a, 'todo'); await page.keyboard.press('Escape');
    assert.deepEqual(await state(ids.a), original, 'Escape leaves task and seed unchanged');
    await choose(ids.a, 'todo'); await decision('confirm'); await saved();
    assert.equal((await state(ids.a)).seed.state, 'destroyed');
    await choose(ids.a, 'doing'); await saved();
    const restarted = await state(ids.a);
    assert.equal(restarted.seed.plantKind, original.seed.plantKind); assert.equal(restarted.seed.ticket, original.seed.ticket);
    await page.locator('#task-notice button').click();
    assert.equal((await state(ids.a)).task.status, 'doing', 'Undo waits for consent before destroying a planted seed');
    await decision('cancel');
    assert.equal((await state(ids.a)).seed.state, 'growing');
    const grip = await page.locator('.card[data-id="' + ids.a + '"] .drag-handle').boundingBox();
    const destination = await page.locator('.col-body[data-col="todo"]').boundingBox();
    await page.mouse.move(grip.x + 10, grip.y + 10); await page.mouse.down();
    await page.mouse.move(destination.x + destination.width / 2, destination.y + 30, { steps: 12 }); await page.mouse.up();
    assert.equal(await page.locator('.task-action-confirm').isVisible(), true, 'pointer withdrawal requests consent');
    await decision('cancel');
    assert.equal((await state(ids.a)).task.status, 'doing');
    assert.equal(await page.locator('.col-body[data-col="doing"] .card[data-id="' + ids.a + '"]').count(), 1, 'cancelled pointer drop restores original column');

    await page.locator('.card[data-id="' + ids.a + '"] .card-title').click();
    await page.locator('#f-title').fill('Draft survives cancellation');
    await page.selectOption('#f-status', 'todo'); await page.locator('#f-save').click();
    await decision('cancel');
    assert.equal(await page.locator('#f-title').inputValue(), 'Draft survives cancellation');
    assert.equal(await page.locator('#f-status').inputValue(), 'todo');
    assert.equal((await state(ids.a)).task.title, original.task.title);
    await page.locator('#f-del').click(); await page.keyboard.press('Escape');
    assert.equal(await page.locator('#f-title').inputValue(), 'Draft survives cancellation', 'delete cancellation also preserves editor fields');
    await page.locator('#f-cancel').click(); await decision('cancel');
    assert.equal(await page.locator('#f-title').inputValue(), 'Draft survives cancellation');
    await page.locator('#f-cancel').click(); await decision('confirm');
    assert.equal(await page.locator('#modal-root').isHidden(), true);

    await page.locator('.card[data-id="' + ids.a + '"]').focus(); await page.keyboard.press('Alt+ArrowLeft');
    assert.equal(await page.locator('.task-action-confirm').isVisible(), true, 'keyboard withdrawals require confirmation');
    await decision('cancel');
    await page.locator('#board-complete-project').click();
    assert.equal(await page.locator('#project-complete-continue').count(), 1, 'unfinished project cannot archive');
    await page.locator('#project-complete-cancel').click();
    await choose(ids.a, 'done'); await saved();
    await page.locator('#board-clear-completed').click();
    assert.match(await page.locator('.task-action-confirm').innerText(), /成熟花朵会自动收获/);
    assert.match(await page.locator('.task-action-confirm').innerText(), /图鉴次数、植物伙伴、项目花朵与完成历史都会保留/);
    await decision('cancel');
    assert.ok((await state(ids.a)).task);
    await page.locator('#board-clear-completed').click(); await decision('confirm'); await saved();
    assert.equal((await state(ids.a)).task, null); assert.equal((await state(ids.a)).seed.state, 'harvested');
    assert.ok((await state(ids.c)).task, 'project-scoped cleanup leaves other project done tasks');
    await choose(ids.b, 'done'); await saved();
    await page.locator('#board-complete-project').click();
    await page.setViewportSize({ width: 390, height: 844 });
    assert.equal(await page.locator('.task-action-confirm').evaluate(el => el.scrollWidth <= el.clientWidth + 1), true, 'archive dialog fits a narrow viewport');
    await page.screenshot({ path: path.join(temporary, 'archive-confirm.png') });
    await decision('confirm'); await saved();
    const archive = await page.evaluate(id => ({ project: TracerModel.findProject(Tracer.store.data, id), planet: TaskGarden.read(Tracer.store.data).planets.find(p => p.id === id) }), ids.p);
    assert.equal(archive.project.status, 'completed'); assert.equal(archive.planet.flowers.length, 2, 'cleared and current flowers both join planet');
    assert.equal(archive.planet.taskCount, 2, 'clearing completed tasks preserves the archived unique task count');
    assert.deepEqual(archive.planet.flowers.map(s => s.taskId).sort(), [ids.a, ids.b].sort());
    assert.equal(await page.locator('.proj-item[data-id="' + ids.p + '"]').count(), 0, 'archived project leaves active sidebar');
    await page.setViewportSize({ width: 1440, height: 1000 });
    await page.evaluate(() => Tracer.openProject(null));
    assert.equal(await page.locator('.card[data-id="' + ids.b + '"]').count(), 0, 'archived tasks leave active board');
    await page.locator('#new-btn').click();
    assert.equal(await page.locator('#f-proj option[value="' + ids.p + '"]').count(), 0, 'archived project cannot receive a new task');
    await page.locator('#f-cancel').click();
    await page.locator('#board-clear-completed').click(); await decision('confirm'); await saved();
    assert.ok((await state(ids.b)).task, 'all-active cleanup retains archived task records');
    await page.reload(); await page.waitForFunction(() => window.Tracer?.store?.data);
    assert.equal((await state(ids.a)).seed.state, 'harvested');
    assert.equal((await page.evaluate(id => TaskGarden.read(Tracer.store.data).planets.find(p => p.id === id), ids.p)).flowers.length, 2);
    await page.selectOption('#language-select', 'en'); await page.evaluate(() => Tracer.openProject(null));
    assert.match(await page.locator('#board-clear-completed').innerText(), /Clear completed/);
    const removal = await page.evaluate(() => {
      const ws = Tracer.store.data, project = TracerModel.addProject(ws, { name: 'Delete growing plants' });
      const task = TracerModel.addTask(ws, { title: 'Growing seed', projectId: project.id, status: 'doing' });
      Tracer.touch(); Tracer.redraw(); return { project: project.id, task: task.id };
    });
    await saved();
    await page.locator('[data-delete-project="' + removal.project + '"]').click();
    assert.match(await page.locator('.project-delete-dialog').innerText(), /Unharvested plants.*destroyed/);
    const beforeDelete = await state(removal.task);
    await page.locator('#project-delete-cancel').click();
    assert.deepEqual(await state(removal.task), beforeDelete, 'project delete cancel does not destroy its plant');
    await page.locator('[data-delete-project="' + removal.project + '"]').click(); await page.locator('#project-delete-confirm').click(); await saved();
    assert.equal((await state(removal.task)).seed.state, 'destroyed');
    assert.ok((await state(removal.task)).seed.retiredAt);
    const staleEditor = await page.evaluate(() => {
      const ws = Tracer.store.data, project = TracerModel.addProject(ws, { name: 'Archived while editing' });
      const task = TracerModel.addTask(ws, { title: 'Preserve this title', projectId: project.id, status: 'doing' });
      TracerModel.moveTask(ws, task.id, 'done'); Tracer.touch(); Tracer.redraw(); Tracer.openTask(task.id);
      return { project: project.id, task: task.id };
    });
    await page.locator('#f-title').fill('Must not change an archived record');
    await page.evaluate(id => { TracerModel.completeProject(Tracer.store.data, id); Tracer.touch(); }, staleEditor.project);
    await saved(); await page.locator('#f-save').click();
    assert.match(await page.locator('#task-error').innerText(), /archived/);
    assert.equal((await state(staleEditor.task)).task.title, 'Preserve this title');
    await page.locator('#f-cancel').click(); await decision('confirm');
    assert.deepEqual(errors, []);
    console.log('PASS: destructive dropdown, pointer, keyboard and Undo cancellation, stable seed replay, editor draft preservation, unfinished archive guard, project-scoped cleanup, auto-harvest, archive with cleared flowers, active-only navigation, narrow dialog, bilingual labels and reload.');
    console.log('Screenshots: ' + temporary);
  } finally {
    await browser.close(); await new Promise(resolve => server.close(resolve));
  }
})().catch(error => { console.error(error); process.exitCode = 1; });
