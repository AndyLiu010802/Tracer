'use strict';
const assert=require('node:assert/strict'),path=require('node:path');
module.exports=async function checkAvatar(page,folder){
  const preview=page.locator('.account-avatar-preview'),color=page.locator('#account-icon-color');
  assert.equal(await page.locator('[data-avatar]').count(),20);
  assert.equal(await color.inputValue(),'#000000');
  await page.locator('[data-avatar="leo"]').click();
  assert.equal(await preview.evaluate(n=>getComputedStyle(n).color),'rgb(0, 0, 0)');
  await color.fill('#7352a1');await color.dispatchEvent('input');
  assert.equal(await preview.evaluate(n=>getComputedStyle(n).color),'rgb(115, 82, 161)');
  await page.locator('#account-profile-save').click();
  await page.waitForFunction(()=>document.getElementById('account-open').style.color==='rgb(115, 82, 161)');
  await page.locator('#account-dialog').screenshot({path:path.join(folder,'avatar-symbols.png')});
  await page.reload();await page.locator('#account-open').click();
  assert.equal(await color.inputValue(),'#7352a1');
  assert.equal(await page.locator('[data-avatar="leo"]').getAttribute('aria-pressed'),'true');
  await page.getByRole('button',{name:'恢复黑色',exact:true}).click();
  assert.equal(await color.inputValue(),'#000000');
  const fixture=await page.evaluate(()=>{const c=document.createElement('canvas');c.width=600;c.height=300;const x=c.getContext('2d');x.fillStyle='#93b4cf';x.fillRect(0,0,600,300);x.fillStyle='#eca274';x.fillRect(0,0,260,300);x.fillStyle='#20384a';x.beginPath();x.arc(300,150,80,0,Math.PI*2);x.fill();return c.toDataURL('image/png').split(',')[1];});
  const upload=()=>page.locator('#account-avatar-file').setInputFiles({name:'crop-fixture.png',mimeType:'image/png',buffer:Buffer.from(fixture,'base64')});
  await upload();await page.locator('#account-crop-canvas').waitFor();
  await page.locator('#account-profile-save').click();
  await page.waitForFunction(()=>document.getElementById('account-notice').textContent.includes('裁剪'));
  const canvas=page.locator('#account-crop-canvas');
  const before=await canvas.evaluate(c=>c.toDataURL());
  await page.locator('#account-crop-zoom').fill('1.6');await page.locator('#account-crop-zoom').dispatchEvent('input');
  await canvas.scrollIntoViewIfNeeded();const rect=await canvas.boundingBox();
  await page.mouse.move(rect.x+rect.width/2,rect.y+rect.height/2);await page.mouse.down();await page.mouse.move(rect.x+rect.width*.65,rect.y+rect.height*.6,{steps:8});await page.mouse.up();
  assert.ok(Number(await canvas.getAttribute('data-crop-x'))>0);
  assert.ok(Number(await canvas.getAttribute('data-crop-y'))>0);
  assert.notEqual(await canvas.evaluate(c=>c.toDataURL()),before);
  await canvas.press('ArrowLeft');
  await page.locator('.account-crop-host').screenshot({path:path.join(folder,'avatar-crop.png')});
  for(const width of [390,320]){await page.setViewportSize({width,height:900});assert.equal(await page.locator('#account-dialog').evaluate(d=>d.scrollWidth<=d.clientWidth+1),true);}
  await page.setViewportSize({width:1440,height:1000});
  await page.locator('#account-crop-apply').click();
  assert.equal(await color.isDisabled(),true);
  const cropped=await preview.locator('img').getAttribute('src');
  await upload();await page.locator('#account-crop-canvas').waitFor();
  await page.locator('.account-crop-actions').getByRole('button',{name:'取消',exact:true}).click();
  assert.equal(await preview.locator('img').getAttribute('src'),cropped);
  await page.locator('#account-profile-save').click();
  await page.waitForFunction(expected=>document.querySelector('#account-open img')?.src===expected,cropped);
  await page.reload();await page.locator('#account-open').click();
  assert.equal(await preview.locator('img').getAttribute('src'),cropped);
  assert.equal(await preview.locator('img').evaluate(i=>i.naturalWidth),192);
  await page.locator('#account-dialog').screenshot({path:path.join(folder,'avatar-uploaded.png')});
};
